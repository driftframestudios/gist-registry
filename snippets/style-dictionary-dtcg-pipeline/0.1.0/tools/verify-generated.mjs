import { lstat, opendir } from "node:fs/promises";
import { resolve, sep } from "node:path";
import { BUILD_MATRIX, coordinateId } from "../config/build-matrix.mjs";
import {
  DEFAULT_LIMITS,
  compareOrdinal,
  normalizeCssName,
  readBoundedFile,
  sha256,
  stableStringify,
} from "../src/contract.mjs";
import { parseOutputArgument } from "./paths.mjs";

function containedPath(root, candidate) {
  const resolvedRoot = resolve(root);
  const resolvedCandidate = resolve(candidate);
  if (resolvedCandidate !== resolvedRoot && !resolvedCandidate.startsWith(`${resolvedRoot}${sep}`)) {
    throw new Error(`${resolvedCandidate} escapes the generated output root`);
  }
  return resolvedCandidate;
}

async function requireDirectory(path) {
  const entry = await lstat(path);
  if (entry.isSymbolicLink() || !entry.isDirectory()) {
    throw new Error(`${path} must be a regular directory`);
  }
}

async function readRegular(root, candidate, maxBytes) {
  const path = containedPath(root, candidate);
  const entry = await lstat(path);
  if (entry.isSymbolicLink() || !entry.isFile()) throw new Error(`${path} must be a regular file`);
  return readBoundedFile(path, {
    maxBytes,
    stage: "target_verification",
    dimension: "generated_bytes",
    label: "Generated artifact",
    restartFrom: "candidate_build",
  });
}

async function boundedDirectoryNames(path, maxEntries) {
  const names = [];
  const directory = await opendir(path);
  try {
    for await (const entry of directory) {
      names.push(entry.name);
      if (names.length > maxEntries) {
        throw new Error(`${path} generated file inventory exceeds the configured envelope`);
      }
    }
  } finally {
    await directory.close().catch(error => {
      if (error.code !== "ERR_DIR_CLOSED") throw error;
    });
  }
  return names.sort(compareOrdinal);
}

function verifyCss(source, coordinate) {
  if (!source.includes(":root {")) throw new Error(`${coordinate} CSS requires a :root block`);
  let depth = 0;
  for (const character of source) {
    if (character === "{") depth += 1;
    if (character === "}") depth -= 1;
    if (depth < 0) throw new Error(`${coordinate} CSS closes a block before it opens`);
  }
  if (depth !== 0) throw new Error(`${coordinate} CSS requires balanced blocks`);
  const names = [...source.matchAll(/--([a-z0-9-]+)\s*:/gu)].map(match => match[1]);
  if (names.length === 0) throw new Error(`${coordinate} CSS requires custom properties`);
  if (new Set(names).size !== names.length) throw new Error(`${coordinate} CSS repeats a custom property`);
  return names.length;
}

function equalStringSets(left, right) {
  return stableStringify([...new Set(left)].sort(compareOrdinal))
    === stableStringify([...new Set(right)].sort(compareOrdinal));
}

function parseJavascriptTokens(source, coordinate) {
  const lines = source.split("\n");
  const expectedHeader = "// Generated by tokens.js; revise authored tokens and regenerate.";
  if (
    lines[0] !== expectedHeader
    || lines[1] !== "export const tokens = Object.freeze({"
    || lines.at(-3) !== "});"
    || lines.at(-2) !== "export default tokens;"
    || lines.at(-1) !== ""
  ) {
    throw new Error(`${coordinate} JavaScript requires the complete generated static-module structure`);
  }
  const entries = lines.slice(2, -3);
  const names = [];
  for (const line of entries) {
    const match = line.match(/^  ("(?:[^"\\]|\\.)*"): (.+),$/u);
    if (!match) throw new Error(`${coordinate} JavaScript contains a value outside the generated token-entry structure`);
    let name;
    try {
      name = JSON.parse(match[1]);
      if (match[2] !== "undefined") JSON.parse(match[2]);
    } catch {
      throw new Error(`${coordinate} JavaScript token entries require JSON literals or the generated undefined sentinel`);
    }
    if (typeof name !== "string" || name.length === 0) {
      throw new Error(`${coordinate} JavaScript token names require non-empty string literals`);
    }
    names.push(name);
  }
  if (new Set(names).size !== names.length) throw new Error(`${coordinate} JavaScript repeats a token name`);
  if (stableStringify(names) !== stableStringify([...names].sort(compareOrdinal))) {
    throw new Error(`${coordinate} JavaScript token names require stable lexical order`);
  }
  return names;
}

function parseDeclarationTokens(source, coordinate) {
  const lines = source.split("\n");
  const expectedHeader = "// Generated by tokens.d.ts; revise authored tokens and regenerate.";
  const declaration = "export declare const tokens: Readonly<Record<TokenName, string | number | boolean | Readonly<Record<string, unknown>>>>;";
  if (
    lines.length !== 5
    || lines[0] !== expectedHeader
    || !lines[1].startsWith("export type TokenName = ")
    || !lines[1].endsWith(";")
    || lines[2] !== declaration
    || lines[3] !== "export default tokens;"
    || lines[4] !== ""
  ) {
    throw new Error(`${coordinate} declaration file requires the complete generated TokenName contract`);
  }
  const union = lines[1].slice("export type TokenName = ".length, -1);
  const literals = [...union.matchAll(/"(?:[^"\\]|\\.)*"/gu)].map(match => match[0]);
  if (literals.join(" | ") !== union) {
    throw new Error(`${coordinate} declaration TokenName members require a literal-only union`);
  }
  const names = literals.map(literal => {
    try {
      return JSON.parse(literal);
    } catch {
      throw new Error(`${coordinate} declaration TokenName members require string literals`);
    }
  });
  if (names.some(name => typeof name !== "string" || name.length === 0)) {
    throw new Error(`${coordinate} declaration TokenName members require non-empty strings`);
  }
  if (new Set(names).size !== names.length) throw new Error(`${coordinate} declaration repeats a token name`);
  return names;
}

export async function verifyGenerated({ outputRoot }) {
  const verifiedRoot = resolve(outputRoot);
  await requireDirectory(verifiedRoot);
  const expectedArtifactCount = BUILD_MATRIX.length * 3;
  if (expectedArtifactCount > DEFAULT_LIMITS.generatedFiles) {
    throw new Error("generated file count exceeds the configured envelope");
  }
  const artifacts = [];
  let generatedBytes = 0;
  for (const coordinate of BUILD_MATRIX) {
    const id = coordinateId(coordinate);
    const root = containedPath(verifiedRoot, resolve(verifiedRoot, id));
    await requireDirectory(root);
    const expectedFiles = ["tokens.css", "tokens.d.ts", "tokens.js"];
    const observedFiles = await boundedDirectoryNames(root, expectedFiles.length);
    if (stableStringify(observedFiles) !== stableStringify(expectedFiles)) {
      throw new Error(`${id} generated file inventory differs from the declared contract`);
    }
    const fileBytes = [];
    for (const file of expectedFiles) {
      const remainingBytes = DEFAULT_LIMITS.generatedBytes - generatedBytes;
      const bytes = await readRegular(verifiedRoot, resolve(root, file), remainingBytes);
      generatedBytes += bytes.byteLength;
      fileBytes.push(bytes);
    }
    const [cssBytes, declarationBytes, jsBytes] = fileBytes;
    const cssCount = verifyCss(cssBytes.toString("utf8"), id);
    const javascriptNames = parseJavascriptTokens(jsBytes.toString("utf8"), id);
    const declarationNames = parseDeclarationTokens(declarationBytes.toString("utf8"), id);
    const cssNames = [...cssBytes.toString("utf8").matchAll(/--([a-z0-9-]+)\s*:/gu)].map(match => match[1]);
    if (
      javascriptNames.length !== cssCount
      || !equalStringSets(declarationNames, javascriptNames)
      || !equalStringSets(cssNames, javascriptNames.map(normalizeCssName))
    ) {
      throw new Error(`${id} CSS, JavaScript, and declaration token inventories must agree`);
    }
    for (const [file, bytes] of expectedFiles.map((file, index) => [file, [cssBytes, declarationBytes, jsBytes][index]])) {
      artifacts.push({ coordinate: id, path: `${id}/${file}`, bytes: bytes.byteLength, sha256: sha256(bytes) });
    }
  }
  if (artifacts.length > DEFAULT_LIMITS.generatedFiles) {
    throw new Error("generated file count exceeds the configured envelope");
  }
  if (generatedBytes > DEFAULT_LIMITS.generatedBytes) {
    throw new Error("generated bytes exceed the configured envelope");
  }
  artifacts.sort((left, right) => compareOrdinal(left.path, right.path));
  return { artifactCount: artifacts.length, generatedBytes, artifacts };
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const outputRoot = parseOutputArgument(process.argv.slice(2), ".artifacts/candidate");
  verifyGenerated({ outputRoot })
    .then(result => process.stdout.write(stableStringify(result)))
    .catch(error => {
      process.stderr.write(`${stableStringify({ code: "TARGET_VERIFICATION_FAILED", message: error.message })}`);
      process.exitCode = 1;
    });
}
