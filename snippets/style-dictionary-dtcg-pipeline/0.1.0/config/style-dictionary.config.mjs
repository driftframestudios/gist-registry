import { relative } from "node:path";
import { compareOrdinal } from "../src/contract.mjs";

function sortedTokens(dictionary) {
  return [...dictionary.allTokens].sort((left, right) => compareOrdinal(left.path.join("."), right.path.join(".")));
}

function jsLiteral(value) {
  return JSON.stringify(value);
}

export function registerKindlightFormats(StyleDictionary) {
  const registrations = [
    {
      name: "kindlight/esm",
      format: ({ dictionary, file }) => {
        const entries = sortedTokens(dictionary)
          .map(token => `  ${JSON.stringify(token.path.join("."))}: ${jsLiteral(token.value)},`)
          .join("\n");
        return `// Generated by ${file.destination}; revise authored tokens and regenerate.\nexport const tokens = Object.freeze({\n${entries}\n});\nexport default tokens;\n`;
      },
    },
    {
      name: "kindlight/types",
      format: ({ dictionary, file }) => {
        const keys = sortedTokens(dictionary).map(token => JSON.stringify(token.path.join("."))).join(" | ");
        return `// Generated by ${file.destination}; revise authored tokens and regenerate.\nexport type TokenName = ${keys};\nexport declare const tokens: Readonly<Record<TokenName, string | number | boolean | Readonly<Record<string, unknown>>>>;\nexport default tokens;\n`;
      },
    },
  ];
  for (const registration of registrations) {
    try {
      StyleDictionary.registerFormat(registration);
    } catch (error) {
      if (!String(error.message).includes("already registered")) throw error;
    }
  }
}

export function createStyleDictionaryConfig({ sourcePaths, buildPath }) {
  const normalizedBuildPath = buildPath.endsWith("/") ? buildPath : `${buildPath}/`;
  return {
    usesDtcg: true,
    source: sourcePaths,
    platforms: {
      css: {
        transformGroup: "css",
        buildPath: normalizedBuildPath,
        files: [
          {
            destination: "tokens.css",
            format: "css/variables",
            options: { outputReferences: true, showFileHeader: false },
          },
        ],
      },
      javascript: {
        transformGroup: "js",
        buildPath: normalizedBuildPath,
        files: [
          { destination: "tokens.js", format: "kindlight/esm" },
          { destination: "tokens.d.ts", format: "kindlight/types" },
        ],
      },
    },
    log: { verbosity: "silent" },
    metadata: {
      sourcePaths: sourcePaths.map(path => relative(process.cwd(), path)),
    },
  };
}
