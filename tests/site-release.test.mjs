import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import test from "node:test";
import { checkSiteRelease, verifySiteIdentity } from "../tools/check-site-release.mjs";
import { buildPages, checkProjection } from "../tools/build-pages.mjs";

async function fixture(action) {
  const root = await mkdtemp(join(tmpdir(), "gist-release-identity-"));
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  try {
    git("init", "-b", "main");
    git("config", "user.name", "Synthetic release test");
    git("config", "user.email", "fixture@example.invalid");
    await writeFile(join(root, "source.txt"), "accepted source\n");
    git("add", "."); git("commit", "-m", "Accepted fixture");
    const sourceRevision = git("rev-parse", "HEAD");
    git("update-ref", "refs/remotes/origin/main", sourceRevision);
    git("tag", "-a", "site/v0.1.0", "-m", "Synthetic source release");
    await action({ root, git, tag: "site/v0.1.0", manifest: {
      sourceRevision, sourceStanding: "accepted_revision", projectionOwner: "gist-registry-pages-builder",
    } });
  } finally { await rm(root, { recursive: true, force: true }); }
}

test("site identity binds an annotated tag, accepted remote source and projection", async () => {
  await fixture(input => assert.deepEqual(verifySiteIdentity(input), {
    tag: input.tag, sourceRevision: input.manifest.sourceRevision,
  }));
});

test("missing, lightweight and mismatched tags hold promotion", async () => {
  await fixture(input => {
    assert.throws(() => verifySiteIdentity({ ...input, tag: undefined }), /exact site/u);
    assert.throws(() => verifySiteIdentity({ ...input, tag: "site/v0.2.0" }));
    input.git("tag", "site/v0.2.0");
    assert.throws(() => verifySiteIdentity({ ...input, tag: "site/v0.2.0" }), /annotated tag/u);
    input.git("commit", "--allow-empty", "-m", "Next accepted fixture");
    input.git("update-ref", "refs/remotes/origin/main", input.git("rev-parse", "HEAD"));
    assert.throws(() => verifySiteIdentity(input), /identify the accepted source/u);
  });
});

test("stale remote, dirty source, mismatched projection and fixture standing hold promotion", async () => {
  await fixture(async input => {
    for (const change of [
      { sourceRevision: "0".repeat(40) }, { sourceStanding: "test_fixture" }, { projectionOwner: "other" },
    ]) assert.throws(() => verifySiteIdentity({ ...input, manifest: { ...input.manifest, ...change } }));
    await writeFile(join(input.root, "unreviewed.txt"), "local change\n");
    assert.throws(() => verifySiteIdentity(input), /clean/u);
    input.git("add", "."); input.git("commit", "-m", "Unaccepted fixture");
    assert.throws(() => verifySiteIdentity(input), /freshly fetched origin\/main/u);
  });
});


test("site release rejects self-consistent generated bytes that differ from its accepted source", async () => {
  const container = await mkdtemp(join(tmpdir(), "gist-release-projection-"));
  const root = join(container, "source");
  const output = join(container, "pages");
  const repository = resolve(import.meta.dirname, "..");
  const git = (...args) => execFileSync("git", args, {
    cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"],
  }).trim();
  try {
    // A local clone retains the source/history owners required by the real builder.
    execFileSync("git", ["clone", "--quiet", "--no-local", "--no-tags", repository, root], {
      stdio: ["ignore", "pipe", "pipe"],
    });
    git("fetch", "--quiet", "--no-tags", repository,
      "refs/remotes/origin/docs:refs/remotes/origin/docs");
    git("config", "user.name", "Synthetic release test");
    git("config", "user.email", "fixture@example.invalid");
    const revision = git("rev-parse", "HEAD");
    git("update-ref", "refs/remotes/origin/main", revision);
    const tag = "site/v0.0.0";
    git("-c", "tag.gpgsign=false", "tag", "-a", tag, "-m", "Synthetic source release");
    await buildPages({ root, output });
    assert.equal((await checkSiteRelease({ root, output, tag })).standing,
      "ready_for_authorized_docs_promotion");

    const manifestPath = join(output, "projection-manifest.json");
    const originalManifest = await readFile(manifestPath);
    const indexPath = join(output, "index.html");
    const originalIndex = await readFile(indexPath);
    const changedIndex = Buffer.concat([originalIndex, Buffer.from("\n<!-- synthetic changed output -->\n")]);
    await writeFile(indexPath, changedIndex);
    const manifest = JSON.parse(originalManifest);
    const entry = manifest.files.find(file => file.path === "index.html");
    assert.ok(entry);
    entry.bytes = changedIndex.length;
    entry.sha256 = createHash("sha256").update(changedIndex).digest("hex");
    await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

    // Internal consistency holds; the release's fresh-source comparison owns rejection.
    await checkProjection({ root, output });
    await assert.rejects(checkSiteRelease({ root, output, tag }),
      /release candidate must equal a fresh accepted-source build/u);
    await writeFile(indexPath, originalIndex);
    await writeFile(manifestPath, originalManifest);
    assert.equal((await checkSiteRelease({ root, output, tag })).standing,
      "ready_for_authorized_docs_promotion");
  } finally {
    await rm(container, { recursive: true, force: true });
  }
});
